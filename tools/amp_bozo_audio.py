"""Build Amplitude's IOP sound modules as native C++ with BozoEngine's offline IRX tools (docs/native-irx.md).

The game loads Sony's LIBSD and SDRDRV (the server 0x80000701 libsdr's sceSdRemote calls) and Harmonix's sound
modules (with Sony's SCRTCHPD, the scratchpad service SOFTFX_S allocates from), SYNTH_S.IRX (the synthesizer, RPC server 0x75433178) and SOFTFX_S.IRX ("softFX", the effects, 0x75433776).
Each module is relocated at a fixed base and translated to C++ (strict mode); amp_audio_modules.h registers the images
with the port's CompiledLibraries. Output is derived from the player's disc: build directory only. From
Shinobido_WOTN_Recomp's tools/shino_bozo_audio.py.

  python -I tools/amp_bozo_audio.py <game dir> <out dir> <BozoEngine dir>
"""
from pathlib import Path
import subprocess
import sys

MODULES = ['LIBSD', 'SDRDRV', 'SCRTCHPD', 'SYNTH_S', 'SOFTFX_S']
FIRST_BASE = 0x45A00
# The native library heap starts after the last image (runtime/amp_audio.cpp).
HEAP_START = 0x90000


def main():
    game, out, engine = (Path(a) for a in sys.argv[1:4])
    out.mkdir(parents=True, exist_ok=True)
    sys.path.insert(0, str(engine / 'tools/native_irx'))
    from relocate import relocate
    from recompile import Module

    lines = ['#pragma once', '// Generated by tools/amp_bozo_audio.py from the player\'s disc: never commit.',
             '#include "bozo/native/compiled_libraries.h"', '#include <iterator>',
             'inline void addAmpAudioImages(bozo::native::irx::CompiledLibraries &host) {']
    base = FIRST_BASE
    for name in MODULES:
        info = relocate(game / 'IOP' / f'{name}.IRX', base, out / name)
        module = Module(str(out / (name + '.json')))
        exports, imports = module.tables()
        subprocess.run([sys.executable, '-I', str(engine / 'tools/native_irx/recompile.py'), str(out / (name + '.json')),
                        '--out', str(out)], check=True)
        data = (out / (name + '.bin')).read_bytes()
        lines += ['{', 'bozo::native::irx::Image image;', f'image.name="{info["name"]}"; image.hash=0x{info["hash"]}ull;',
                  f'image.base={base:#x};image.entry={info["entry"]};image.gp={info["gp"]};']
        lines += ['static const uint8_t bytes[]={'] + [' '.join(f'0x{v:02x},' for v in data[i:i + 32])
                                                     for i in range(0, len(data), 32)]
        lines += ['};', 'image.bytes.assign(std::begin(bytes),std::end(bytes));']
        for label, entries in [('imports', imports), ('exports', exports)]:
            lines += [f'image.{label}={{'] + [f'{{0x{addr:x},"{lib}",{ordinal}}},' for addr, (lib, ordinal) in entries.items()]
            lines += ['};']
        lines += [f'image.nativeLibsd={str(name == "LIBSD").lower()};', 'host.addImage(std::move(image));', '}']
        print(f'{name}: {info["name"]} at {base:#x}, {len(data):#x} bytes')
        base = (base + len(data) + 0xFF) & ~0xFF
    if base > HEAP_START:
        raise SystemExit(f'the images end at {base:#x}, past the heap start {HEAP_START:#x}')
    lines += ['}', f'constexpr uint32_t kAmpAudioHeapStart = {HEAP_START:#x};']
    (out / 'amp_audio_modules.h').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
